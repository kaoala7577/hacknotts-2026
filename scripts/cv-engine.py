import numpy as np 
import cv2
import mediapipe as mp
from pathlib import Path
from fastdtw import fastdtw
from scipy.spatial.distance import euclidean
from enum import Enum

class SignPassMark(float, Enum):
	"""
	pass thresholds for the DTW evaluation. lower is better
	"""
	EXCEPTIONAL = 0.1
	PASS = 0.25
	FAIL = float('inf')

	@classmethod
	def evaluate(self, score: float) -> 'SignPassMark':
		"""
		evaluate whether a DTW distance's evaluated float value shows that the input video is close to the reference videos or not

		Args:
			score (float): the similarity score between the input video and the references, generated by
				SignRecognitionEngine.compute_dtw_distance()
		
		Returns:
			SignPassMark: an enum representing a failure (no match), a pass (match), or exceptional pass
				(high scoring pass that can be added as future reference data)
		"""
		if score <= self.EXCEPTIONAL:
			return self.EXCEPTIONAL
		elif score <= self.PASS:
			return self.PASS
		else:
			return self.FAIL

class SignRecognitionEngine:
	def __init__(self, task_file_path: str = str(Path(__file__).parent / "hand_landmarker.task")):
		BaseOptions = mp.tasks.BaseOptions
		HandLandmarkerOptions = mp.tasks.vision.HandLandmarkerOptions
		# HandLandmarkerResult = mp.tasks.vision.HandLandmarkerResult
		VisionRunningMode = mp.tasks.vision.RunningMode

		# def print_result(result: HandLandmarkerResult, output_image: mp.Image, timestamp_ms: int):
    	# 	print('hand landmarker result: {}'.format(result))

		self.options = HandLandmarkerOptions(
			base_options=BaseOptions(model_asset_path=task_file_path),
			num_hands=2,
			running_mode=VisionRunningMode.VIDEO
			#running_mode=VisionRunningMode.LIVE_STREAM,
			#result_callback=print_result
		)

	def start_detecting(self) -> None:
		self.detector = mp.tasks.vision.HandLandmarker.create_from_options(self.options)

	def stop_detecting(self) -> None:
		self.detector.close()

	def video_to_mp_image(self, path: str) -> np.ndarray:
		"""
		converts an mp4 video's path to its constituent frames and their timestamps

		Args:
			path (str): the path to the mp4 file

		Raises:
			FileNotFoundError: path is invalid

		Returns:
			np.ndarray: array containing tuples of mediapipe images (video frames) and their timestamps in milliseconds (int)
		"""
		cap = cv2.VideoCapture(path)

		if not cap.isOpened():
			raise FileNotFoundError(f"Could not open {path}")
		
		fps = cap.get(cv2.CAP_PROP_FPS)
		frame_index = 0

		frames = []

		while cap.isOpened():
			ret, frame = cap.read()
			if not ret:
				break

			rgb_frame = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
			mp_image = mp.Image(image_format=mp.ImageFormat.SRGB, data=rgb_frame)
			timestamp_ms = int((frame_index / fps) * 1000)

			frames.append((mp_image, timestamp_ms))
			frame_index += 1
		cap.release()
		cv2.destroyAllWindows()

		return frames

	def videos_to_mp_image(self, paths: np.ndarray) -> np.ndarray:
		"""
		converts an array of mp4 video paths to their frames and timestamps

		Args:
			paths (np.ndarray): an array of mp4 video paths

		Returns:
			np.ndarray: an array containing an array for each path containing frames (mediapipe images) and timestamps (ints)
		"""
		images = []
		for path in paths: images.append(self.video_to_mp_image(path))
		return images
	
	def extract_landmarks(self, cv_frame: np.ndarray) -> np.ndarray:
		"""
		puts an array of video frames and their timestamps through the mediapipe hand detection model to generate joint landmarks,
		which are then labelled per hand to provide a uniform 126-node (2 hands * 21 joints * 3 coordinates) output

		Args:
			cv_frame (np.ndarray): an array containing tuples of video frames and their timestamps

		Returns:
			np.ndarray: a 2D float32 array where each row is a flattened array of 126 coordinates for evaluation
		"""
		self.start_detecting()
		sequence_data = []
		
		for frame in cv_frame:
			video, timestamp_ms = frame
			detection_result = self.detector.detect_for_video(video, timestamp_ms)

			left_hand = [0.0] * 63 # 21 joints * 3 (xyz) coords
			right_hand = [0.] * 63

			if detection_result.hand_landmarks and detection_result.handedness:
				for landmarks, hand_side in zip(detection_result.hand_landmarks, detection_result.handedness):
					hand_label = hand_side[0].category_name

					flattened = []
					for landmark in landmarks:
						flattened.extend([landmark.x, landmark.y, landmark.z])

					if hand_label == 'Left':
						left_hand = flattened
					elif hand_label == 'Right':
						right_hand = flattened

			combined = left_hand + right_hand
			sequence_data.append(combined)
		
		self.stop_detecting()
		return np.array(sequence_data, dtype=np.float32)

	def compute_dtw_distance(self, references: np.ndarray, comparison: np.ndarray) -> np.ndarray:
		"""
		use the dynamic time warping algorithm to determine how similar the input video is to the reference videos

		Args:
			references (np.ndarray): an array of landmark (float32) data for each reference video
			comparison (np.ndarray): an array of landmark (float32) data for the input video

		Returns:
			np.ndarray: a float32 array the same size as the number of comparisons, showing the DTW distance from the input video
		"""
		distances = []
		for refs in references:
			dtw_distance, warp = fastdtw(comparison, refs, dist=euclidean)
			warp_size = len(warp)
			# account for differing video lengths
			normalised_distance = dtw_distance / warp_size
			distances.append(normalised_distance)
		return np.array(distances, dtype=np.float32)

	def evaluate_sign(self, references: np.ndarray, comparison: np.ndarray) -> SignPassMark:
		"""
		evaluation of whether the input video matched the references videos (by taking the closest DTW distance), with a pass/fail

		Args:
			references (np.ndarray): an array of landmark (float32) data for each reference video
			comparison (np.ndarray): an array of landmark (float32) data for the input video

		Returns:
			SignPassMark: an enum demonstrating whether the input video was close to the reference videos or not
		"""
		distances = self.compute_dtw_distance(references, comparison)
		closest = float(np.min(distances))
		result_tier = SignPassMark.evaluate(closest)
		print(f"Result: {closest:.2f} ({result_tier.name})")
		return result_tier
		
	def select_best_take(self, references: np.ndarray) -> int: 
		"""
		select the most "middling" take from an array of reference videos, to determine which one should have its video saved for use
		in the flashcards

		Args:
			references (np.ndarray): an array of landmark (float32) data for each reference video

		Returns:
			int: the index of which video should be saved
		"""
		distances = []
		for i, to_compare in enumerate(references):
			compare_to = references[:i] + references[i+1:]
			dtw_distance = self.compute_dtw_distance(compare_to, to_compare)
			average_distance = float(np.mean(dtw_distance))
			distances.append(average_distance)
		best_take = distances.index(min(distances))
		return best_take
